
%% setValveStimuli
%   Opens a GUI to check and modify valve/stimulus assignmnets. 
%   
%   Define up to 4 stimulus types and assign each of valves 1-8
%   to one of those stimulus slots.
%
%   Saved file: 'valve_config.mat' next to this .m file.
%   Loaded struct 'config' has fields:
%       config.stimuli        - pool of possible stimulus names
%       config.stimulus_slots - 1x4 cell; name assigned to "Stimulus k"
%       config.valve_slots    - 1x8 double; slot index per valve (0 = none)
%       config.assignments    - 1x8 cell; resolved stimulus name per valve

% Original script generated by DeepSeek. Modified, validated, and integrated by TVD. 

function setValveStimuli()

    % ---------------- Default configuration (edit freely) ----------------
    defaultStimuli       = {'Water', 'Sucrose 5%', 'Quinine', 'Ethanol', ...
                            'Air', 'Odor A', 'Odor B'};
    defaultStimulusSlots = {'Water', 'Sucrose 5%', 'Quinine', 'Ethanol'};
    defaultValveSlots    = [1 1 2 2 3 3 4 4];   % valve v -> slot index
    % ---------------------------------------------------------------------

    nValves   = 8;
    nSlots    = 4;
    noneLabel = '-- none --';

    configFile = fullfile(fileparts(which('valve_config.mat')), 'valve_config.mat');

    if isfile(configFile)
        S             = load(configFile);
        stimuli       = S.config.stimuli;
        stimulusSlots = S.config.stimulus_slots;
        valveSlots    = S.config.valve_slots;
    else
        stimuli       = defaultStimuli;
        stimulusSlots = defaultStimulusSlots;
        valveSlots    = defaultValveSlots;
    end
    stimulusSlots = padCell(stimulusSlots, nSlots);
    valveSlots    = padNum(valveSlots, nValves);
    
    % Check stimulus valve rotations for the current day and update first
    [stim1_valves, stim2_valves] = currentDayConditions; 
    valveSlots(stim1_valves) = 1; 
    valveSlots(stim2_valves) = 2; 

    updating = false;   % reentrancy guard

    % ---------------- Build UI ----------------
    fig = uifigure('Name', 'Valve Stimulus Configuration', ...
                   'Position', [100 100 640 700]);

    main = uigridlayout(fig, [5 1]);
    main.RowHeight  = {22, 'fit', 22, 'fit', 46};
    main.Padding    = [12 12 12 12];
    main.RowSpacing = 10;

    % ---- Section 1: stimulus type definitions ----
    uilabel(main, 'Text', 'Stimulus types (up to 4):', 'FontWeight', 'bold');

    stimGrid = uigridlayout(main, [nSlots 2]);
    stimGrid.ColumnWidth = {110, '1x'};
    stimGrid.RowHeight   = repmat({30}, 1, nSlots);
    stimGrid.RowSpacing  = 6;

    ddStim    = gobjects(1, nSlots);
    stimItems = [{noneLabel}, stimuli];

    for k = 1:nSlots
        uilabel(stimGrid, 'Text', sprintf('Stimulus %d:', k), ...
                'HorizontalAlignment', 'right');
        val = stimulusSlots{k};
        if isempty(val) || ~any(strcmp(stimuli, val))
            val = noneLabel;
        end
        ddStim(k) = uidropdown(stimGrid, 'Items', stimItems, 'Value', val);
        ddStim(k).ValueChangedFcn = @(~,~) onStimChanged();
    end

    % ---- Section 2: valve assignments ----
    uilabel(main, 'Text', 'Valve assignments:', 'FontWeight', 'bold');

    valveGrid = uigridlayout(main, [nValves 2]);
    valveGrid.ColumnWidth = {110, '1x'};
    valveGrid.RowHeight   = repmat({30}, 1, nValves);
    valveGrid.RowSpacing  = 6;

    ddValve = gobjects(1, nValves);
    for v = 1:nValves
        uilabel(valveGrid, 'Text', sprintf('Valve %d:', v), ...
                'HorizontalAlignment', 'right');
        ddValve(v) = uidropdown(valveGrid);
        ddValve(v).UserData = clampSlot(valveSlots(v), nSlots);
        ddValve(v).ValueChangedFcn = @(~,~) onValveChanged(v);
    end
    refreshValveDropdowns();

    % ---- Buttons ----
    btnGrid = uigridlayout(main, [1 4]);
    btnGrid.ColumnWidth   = {'1x','1x','1x','1x'};
    btnGrid.ColumnSpacing = 8;

    uibutton(btnGrid, 'Text', 'Add Stimulus',    'ButtonPushedFcn', @onAdd);
    uibutton(btnGrid, 'Text', 'Remove Stimulus', 'ButtonPushedFcn', @onRemove);
    uibutton(btnGrid, 'Text', 'Cancel',          'ButtonPushedFcn', @(~,~) delete(fig));
    acceptBtn = uibutton(btnGrid, 'Text', 'Accept', 'ButtonPushedFcn', @onAccept);
    acceptBtn.FontWeight = 'bold';

    % ================= Helpers =================
    function labels = slotDisplayLabels()
        labels = cell(1, nSlots);
        for kk = 1:nSlots
            name = ddStim(kk).Value;
            if strcmp(name, noneLabel)
                labels{kk} = sprintf('Stimulus %d (unassigned)', kk);
            else
                labels{kk} = sprintf('Stimulus %d (%s)', kk, name);
            end
        end
    end

    % The one and only safe way to change a uidropdown's Items/Value:
    function safeSetItems(dd, newItems, desiredValue)
        % 1) Current Value must be a member of the CURRENT Items
        if ~any(strcmp(dd.Value, dd.Items))
            dd.Value = dd.Items{1};
        end
        % 2) Now change Items
        dd.Items = newItems;
        % 3) Now set the desired Value (must exist in new Items)
        if any(strcmp(desiredValue, dd.Items))
            dd.Value = desiredValue;
        else
            dd.Value = dd.Items{1};
        end
    end

    function refreshValveDropdowns()
        if updating, return; end
        updating = true;
        try
            labels = slotDisplayLabels();
            items  = [{noneLabel}, labels];
            for vv = 1:nValves
                idx = ddValve(vv).UserData;
                if isempty(idx) || idx < 0 || idx > nSlots
                    idx = 0;
                    ddValve(vv).UserData = 0;
                end
                if idx == 0
                    newVal = noneLabel;
                else
                    newVal = labels{idx};
                end
                safeSetItems(ddValve(vv), items, newVal);
            end
        catch ME
            uialert(fig, ME.message, 'Error refreshing valve list');
        end
        updating = false;
    end

    function onStimChanged()
        if updating, return; end
        refreshValveDropdowns();
    end

    function onValveChanged(v)
        if updating, return; end
        labels = slotDisplayLabels();
        val    = ddValve(v).Value;
        if strcmp(val, noneLabel)
            ddValve(v).UserData = 0;
        else
            idx = find(strcmp(labels, val), 1);
            if isempty(idx), idx = 0; end
            ddValve(v).UserData = idx;
        end
    end

    % ================= Callbacks =================
    function onAdd(~, ~)
        try
            answer = inputdlg('Enter new stimulus name:', 'Add Stimulus', [1 60]);
            figure(fig); drawnow;
            if isempty(answer), return; end
            name = strtrim(answer{1});
            if isempty(name), return; end
            if any(strcmp(stimuli, name))
                uialert(fig, 'That stimulus already exists.', 'Duplicate');
                return;
            end
            stimuli{end+1} = name; %#ok<AGROW>
            items = [{noneLabel}, stimuli];

            updating = true;
            for k = 1:nSlots
                safeSetItems(ddStim(k), items, ddStim(k).Value);
            end
            updating = false;

            refreshValveDropdowns();
        catch ME
            updating = false;
            uialert(fig, ME.message, 'Error adding stimulus');
        end
    end

    function onRemove(~, ~)
        try
            if isempty(stimuli), return; end
            [idx, ok] = listdlg('PromptString', 'Select stimulus to remove:', ...
                                'SelectionMode', 'single', ...
                                'ListString', stimuli, ...
                                'ListSize', [260 220]);
            figure(fig); drawnow;
            if ~ok, return; end
            removed = stimuli{idx};
            stimuli(idx) = [];
            items = [{noneLabel}, stimuli];

            updating = true;
            for k = 1:nSlots
                cur = ddStim(k).Value;
                if strcmp(cur, removed)
                    cur = noneLabel;    % force reassign before Items changes
                end
                safeSetItems(ddStim(k), items, cur);
            end
            updating = false;

            refreshValveDropdowns();
        catch ME
            updating = false;
            uialert(fig, ME.message, 'Error removing stimulus');
        end
    end

    function onAccept(~, ~)
        try
            newStimulusSlots = cell(1, nSlots);
            for k = 1:nSlots
                v = ddStim(k).Value;
                if strcmp(v, noneLabel)
                    newStimulusSlots{k} = '';
                else
                    newStimulusSlots{k} = v;
                end
            end

            newValveSlots = zeros(1, nValves);
            resolved      = cell(1, nValves);
            for v = 1:nValves
                idx = ddValve(v).UserData;
                if isempty(idx) || idx < 1 || idx > nSlots
                    idx = 0;
                end
                newValveSlots(v) = idx;
                if idx == 0
                    resolved{v} = '';
                else
                    resolved{v} = newStimulusSlots{idx};
                end
            end

            config.stimuli        = stimuli;
            config.stimulus_slots = newStimulusSlots;
            config.valve_slots    = newValveSlots;
            config.assignments    = resolved;

            save(configFile, 'config');
            fprintf('Saved valve configuration to %s\n', configFile);
            delete(fig);
        catch ME
            uialert(fig, ME.message, 'Error saving configuration');
        end
    end
end

% -------- small utilities --------
function a = padCell(a, n)
    if ~iscell(a), a = cellstr(a); end
    a = a(:)';
    if numel(a) < n
        a(end+1:n) = {''};
    elseif numel(a) > n
        a = a(1:n);
    end
end

function a = padNum(a, n)
    if ~isnumeric(a), a = zeros(1, n); end
    a = a(:)';
    if numel(a) < n
        a(end+1:n) = 0;
    elseif numel(a) > n
        a = a(1:n);
    end
end

function s = clampSlot(s, nSlots)
    if isempty(s) || ~isscalar(s) || ~isnumeric(s) || s < 0 || s > nSlots
        s = 0;
    end
end